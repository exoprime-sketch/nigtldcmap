#!/usr/bin/env node

/**
 * Generates the public temporal contract consumed by the finder description
 * resolver.
 *
 * The number of years a dataset can actually compare inside one measure is the
 * only honest basis for promising "연도별 변화" on a card. The catalog's
 * referenceYears list counts every year any measure touches, which overstates
 * comparability for 27 elements, so the verified V132 visualization contract is
 * the source instead.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

import { PROJECT_ROOT } from "./v125/audit-utils.mjs";

const CONTRACT_PATH = resolve(
  PROJECT_ROOT,
  "reports/v132/final-public-visualization-contract-v132.json"
);
const OUTPUT_PATH = resolve(
  PROJECT_ROOT,
  "src/data/visualization/publicTemporalContractV135.ts"
);

const contract = JSON.parse(readFileSync(CONTRACT_PATH, "utf8"));
const elements = Array.isArray(contract.elements) ? contract.elements : [];
if (elements.length !== 152) {
  console.error(
    JSON.stringify({
      type: "error",
      task: "build:temporal-contract:v135",
      reason: "expected 152 contract elements",
      actual: elements.length,
    })
  );
  process.exit(1);
}

const rows = elements
  .map((row) => ({
    elementId: String(row.elementId || ""),
    years: Number(row.maxComparableYearCount || 0),
  }))
  .filter((row) => row.elementId)
  .sort((left, right) => left.elementId.localeCompare(right.elementId, "en"));

const body = rows
  .map((row) => `  "${row.elementId}": ${Number.isFinite(row.years) ? row.years : 0},`)
  .join("\n");

const file = `// Generated by scripts/build-public-temporal-contract-v135.mjs
// Source: reports/v132/final-public-visualization-contract-v132.json
// Do not edit by hand; run \`npm run build:temporal-contract:v135\` instead.

/**
 * Largest number of years a single measure of each element can compare. A
 * public screen may only promise a year-over-year reading when this is 3 or
 * more; the catalog's referenceYears list counts years across different
 * measures and therefore overstates comparability.
 */
export const PUBLIC_COMPARABLE_YEAR_COUNT_V135: Readonly<
  Record<string, number>
> = Object.freeze({
${body}
});

export function publicComparableYearCountV135(elementId: string): number {
  return PUBLIC_COMPARABLE_YEAR_COUNT_V135[elementId] ?? 0;
}
`;

writeFileSync(OUTPUT_PATH, file, "utf8");
console.log(
  JSON.stringify({
    type: "summary",
    task: "build:temporal-contract:v135",
    elements: rows.length,
    output: "src/data/visualization/publicTemporalContractV135.ts",
  })
);
