export const PUBLIC_NON_GLOSSARY_ALLOWLIST_V134 = Object.freeze(
  GROUPS_V134.flatMap(({ category, tokens, reason }) =>
    tokens.map((token) =>
      Object.freeze({
        token,
        category,
        reason: reason(token),
      })
    )
  )
);

const PUBLIC_NON_GLOSSARY_ALLOWLIST_BY_TOKEN_V134 = new Map(
  PUBLIC_NON_GLOSSARY_ALLOWLIST_V134.map((entry) => [entry.token, entry])
);

if (
  PUBLIC_NON_GLOSSARY_ALLOWLIST_BY_TOKEN_V134.size !==
  PUBLIC_NON_GLOSSARY_ALLOWLIST_V134.length
) {
  throw new Error("Duplicate token in the V134 public non-glossary allowlist");
}

export function getPublicNonGlossaryAllowanceV134(token) {
  if (typeof token !== "string") return null;
  return PUBLIC_NON_GLOSSARY_ALLOWLIST_BY_TOKEN_V134.get(token.trim()) || null;
}

export function isPublicNonGlossaryTokenAllowedV134(token) {
  return getPublicNonGlossaryAllowanceV134(token) !== null;
}
