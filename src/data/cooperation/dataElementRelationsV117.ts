export function getNextRelatedElementIdsV117(
  elementId: string,
  limit = 5
): Array<{ elementId: string; axis: RelatedEvidenceAxisV117 }> {
  const row = DATA_ELEMENT_RELATION_INDEX_V117.get(elementId);
  if (!row) return [];
  const seen = new Set<string>();
  const result: Array<{ elementId: string; axis: RelatedEvidenceAxisV117 }> =
    [];
  const axisOrder =
    row.cooperationRelevance === "context"
      ? ([
          "policy",
          "finance",
          "projects",
          "partners",
          "risk",
          "enabling",
          "demand",
          "koreaSupply",
        ] as RelatedEvidenceAxisV117[])
      : NEXT_AXIS_ORDER_V117;
  axisOrder.forEach((axis) => {
    row.relatedElements[axis].forEach((relatedId) => {
      if (
        result.length >= limit ||
        seen.has(relatedId) ||
        relatedId === elementId
      )
        return;
      seen.add(relatedId);
      result.push({ elementId: relatedId, axis });
    });
  });
  return result;
}
