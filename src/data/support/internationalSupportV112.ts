export function getInternationalSupportRecordsV112(
  countryIso3?: string | null
): InternationalSupportRecordV112[] {
  if (!countryIso3) return INTERNATIONAL_SUPPORT_RECORDS_V112;
  const iso3 = countryIso3.toUpperCase();
  return INTERNATIONAL_SUPPORT_RECORDS_V112.filter(
    (item) => item.countryIso3 === iso3
  );
}

export function getSupportForCountryTechnologyV112(
  countryIso3: string,
  technologyId?: string | null
): InternationalSupportRecordV112[] {
  if (!technologyId) return [];
  const iso3 = countryIso3.toUpperCase();
  return INTERNATIONAL_SUPPORT_RECORDS_V112.filter(
    (item) =>
      item.countryIso3 === iso3 &&
      item.mappedTechnologyIds.includes(technologyId)
  );
}

export function getCtcnIndexV112(
  countryIso3: string
): CtcnCountryIndexV112 | null {
  return (
    CTCN_COUNTRY_INDEX_V112.find(
      (item) => item.countryIso3 === countryIso3.toUpperCase()
    ) ?? null
  );
}

export function getTechnologyNameKoV112(technologyId: string): string {
  return CLIMATE_TECHNOLOGY_BY_ID.get(technologyId)?.nameKo ?? technologyId;
}

export function summarizeInternationalSupportV112(countryIso3: string) {
  const records = getInternationalSupportRecordsV112(countryIso3);
  const byOrganization = {
    CTCN: records.filter((item) => item.sourceOrganization === "CTCN").length,
    adaptationFund: records.filter(
      (item) => item.sourceOrganization === "Adaptation Fund"
    ).length,
    GEF: records.filter((item) => item.sourceOrganization === "GEF").length,
  };
  const afApproved = records
    .filter((item) => item.sourceOrganization === "Adaptation Fund")
    .reduce((sum, item) => sum + (item.approvedAmountUsd ?? 0), 0);
  return { total: records.length, byOrganization, afApproved };
}
